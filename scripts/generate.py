#!/usr/bin/env python3
"""Writes platform code from shared/: design tokens and English interface text.

  scripts/generate.py          regenerate every output
  scripts/generate.py --check  exit 1 when a generated file differs from shared/ (CI and builds)

Outputs are committed so each platform builds without Python; never edit them by hand.
"""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
shared = root / 'shared'
HEADER = 'Generated by scripts/generate.py from shared/{src}. Do not edit.'

def color(value):
    hexpart, _, alpha = value.partition('/')
    return int(hexpart[1:], 16), float(alpha) if alpha else 1.0

def value_doc(entry):
    return (entry['value'], entry.get('doc')) if isinstance(entry, dict) else (entry, None)

def num(v):
    return str(int(v)) if float(v).is_integer() else repr(float(v))

def swift_rgb(value):
    rgb, alpha = color(value)
    return f'rgb(0x{rgb:06X})' if alpha == 1 else f'rgb(0x{rgb:06X}, {num(alpha)})'

def cs_argb(value):
    rgb, alpha = color(value)
    return f'0x{round(alpha * 255):02X}{rgb:06X}'

def generate():
    tokens = json.loads((shared / 'tokens.json').read_text())
    out = {}
    compiler = (shared / 'blocking/compiler.mjs').read_text().rstrip()
    out['macos/Sources/MicaApp/Blocking/UBlockCompiler.swift'] = '// ' + HEADER.format(src='blocking/compiler.mjs') + '\nimport Foundation\n\nenum UBlockCompiler {\n    static let version = "2"\n    static let module = #"""\n' + compiler + '\n"""#\n}\n'
    version = (shared / 'version.txt').read_text().strip()
    if not re.fullmatch(r'\d+\.\d+\.\d+', version):
        sys.exit('shared/version.txt must contain a three-part numeric version')
    for path in ('macos/Resources/App/Info.plist', 'macos/Sources/MicaDockTile/Info.plist'):
        plist = (root / path).read_text()
        updated, count = re.subn(r'(<key>CFBundleShortVersionString</key>\s*<string>)[^<]+(</string>)',
                                 lambda match: match.group(1) + version + match.group(2), plist)
        if count != 1: sys.exit(f'{path}: expected one CFBundleShortVersionString')
        out[path] = updated
    head = '// ' + HEADER.format(src='tokens.json') + '\n'
    # Swift palette
    lines = [head + 'import AppKit\nimport SwiftUI\n', '/// Light: bright paper shell around a pure white page and panels, near-black neutral ink, light hairlines',
             '/// and soft shadows doing the separation. Dark: warm stone. Both resolve per appearance, Increase Contrast included.', 'enum Palette {']
    for name, e in tokens['palette'].items():
        if 'doc' in e: lines.append(f'    /// {e["doc"]}')
        extra = ''.join(f', {k}: {swift_rgb(e[k])}' for k in ('contrastLight', 'contrastDark') if k in e)
        lines.append(f'    static let {name} = Color.dynamic({swift_rgb(e["light"])}, {swift_rgb(e["dark"])}{extra})')
    lines.append('}\n')
    out['macos/Sources/MicaApp/DesignSystem/Tokens/Palette.swift'] = '\n'.join(lines)
    # Swift geometry
    lines = [head + 'import CoreGraphics\n', '// mica design system: paper-white light and warm stone dark themes, ink primary, soft concentric geometry.',
             '// Every reusable control owns only its own shape; parents own spacing.\n']
    titles = {'chrome': ('Chrome', 'Window chrome geometry. The standard window buttons sit on the vertical center of `bar`.'),
              'space': ('Space', 'Spacing scale.'), 'radius': ('Radius', 'Concentric radii: an inner shape uses the outer radius minus the padding between them.')}
    for group, (type_name, doc) in titles.items():
        lines.append(f'/// {doc}\nenum {type_name} {{')
        for key, entry in tokens[group].items():
            value, d = value_doc(entry)
            if d: lines.append(f'    /// {d}')
            lines.append(f'    static let {key}: CGFloat = {num(value)}')
        lines.append('}\n')
    out['macos/Sources/MicaApp/DesignSystem/Tokens/Geometry.swift'] = '\n'.join(lines)
    m = tokens['motion']
    out['macos/Sources/MicaApp/DesignSystem/Tokens/MotionTokens.swift'] = head + f'''import Foundation

/// Spring parameters in SwiftUI terms: response in seconds, damping fraction. Windows converts them in Mica.Design.
enum MotionTokens {{
    /// {m['hover']['doc']}
    static let hoverDuration = {num(m['hover']['duration'])}
    static let press = (response: {num(m['press']['response'])}, damping: {num(m['press']['damping'])})
    static let snappy = (response: {num(m['snappy']['response'])}, damping: {num(m['snappy']['damping'])})
    static let panel = (response: {num(m['panel']['response'])}, damping: {num(m['panel']['damping'])})
    /// {m['bouncy']['doc']}
    static let bouncy = (response: {num(m['bouncy']['response'])}, damping: {num(m['bouncy']['damping'])})
    /// {m['aura']['doc']}
    static let aura = (icon: {float(m['aura']['icon'])}, lightOpacity: {float(m['aura']['lightOpacity'])}, darkOpacity: {float(m['aura']['darkOpacity'])}, blur: {float(m['aura']['blur'])}, saturation: {float(m['aura']['saturation'])}, restScale: {float(m['aura']['restScale'])}, scale: {float(m['aura']['scale'])}, iconScale: {float(m['aura']['iconScale'])}, iconRise: {float(m['aura']['iconRise'])})
    static let popScale = {num(m['popScale'])}
    /// {m['hoverIntent']['doc']}
    static let hoverIntent = {num(m['hoverIntent']['delay'])}
    /// {m['doneHold']['doc']}
    static let doneHold = {num(m['doneHold']['delay'])}
    /// {m['checkDraw']['doc']}
    static let checkDraw = {num(m['checkDraw']['duration'])}
    /// {m['entrance']['doc']}
    static let entrance = (stagger: {float(m['entrance']['stagger'])}, rise: {float(m['entrance']['rise'])}, cardScale: {float(m['entrance']['cardScale'])}, windowFade: {float(m['entrance']['windowFade'])}, reducedFade: {float(m['entrance']['reducedFade'])})
    /// {m['wordmark']['doc']}
    static let wordmark = (letterStagger: {float(m['wordmark']['letterStagger'])}, letterDuration: {float(m['wordmark']['letterDuration'])}, staggerCap: {float(m['wordmark']['staggerCap'])}, rise: {float(m['wordmark']['rise'])}, spread: {float(m['wordmark']['spread'])}, blur: {float(m['wordmark']['blur'])})
}}
'''
    # C#
    cs = '// ' + HEADER.format(src='tokens.json') + '\nnamespace Mica.Design;\n\n'
    lines = [cs + '/// <summary>Light, dark and high-contrast variants as 0xAARRGGBB.</summary>', 'public static partial class Palette', '{']
    for name, e in tokens['palette'].items():
        if 'doc' in e: lines.append(f'    /// <summary>{e["doc"]}</summary>')
        cl = cs_argb(e.get('contrastLight', e['light'])); cd = cs_argb(e.get('contrastDark', e['dark']))
        lines.append(f'    public static readonly Swatch {name[0].upper() + name[1:]} = new({cs_argb(e["light"])}, {cs_argb(e["dark"])}, {cl}, {cd});')
    lines.append('}\n')
    out['windows/src/Mica.Design/Tokens/Palette.g.cs'] = '\n'.join(lines)
    lines = [cs]
    for group, (type_name, doc) in titles.items():
        lines.append(f'/// <summary>{doc}</summary>\npublic static class {type_name}\n{{')
        for key, entry in tokens[group].items():
            value, d = value_doc(entry)
            if d: lines.append(f'    /// <summary>{d}</summary>')
            lines.append(f'    public const double {key[0].upper() + key[1:]} = {num(value)};')
        lines.append('}\n')
    out['windows/src/Mica.Design/Tokens/Geometry.g.cs'] = '\n'.join(lines)
    out['windows/src/Mica.Design/Tokens/MotionTokens.g.cs'] = cs + f'''/// <summary>Spring parameters in SwiftUI terms (response seconds, damping fraction), converted by <see cref="Motion"/>.</summary>
public static class MotionTokens
{{
    /// <summary>{m['hover']['doc']}</summary>
    public const double HoverDuration = {num(m['hover']['duration'])};
    public static readonly Spring Press = new({num(m['press']['response'])}, {num(m['press']['damping'])});
    public static readonly Spring Snappy = new({num(m['snappy']['response'])}, {num(m['snappy']['damping'])});
    public static readonly Spring Panel = new({num(m['panel']['response'])}, {num(m['panel']['damping'])});
    /// <summary>{m['bouncy']['doc']}</summary>
    public static readonly Spring Bouncy = new({num(m['bouncy']['response'])}, {num(m['bouncy']['damping'])});
    /// <summary>{m['aura']['doc']}</summary>
    public static class Aura
    {{
        public const double Icon = {num(m['aura']['icon'])};
        public const double LightOpacity = {num(m['aura']['lightOpacity'])};
        public const double DarkOpacity = {num(m['aura']['darkOpacity'])};
        public const double Blur = {num(m['aura']['blur'])};
        public const double Saturation = {num(m['aura']['saturation'])};
        public const double RestScale = {num(m['aura']['restScale'])};
        public const double Scale = {num(m['aura']['scale'])};
        public const double IconScale = {num(m['aura']['iconScale'])};
        public const double IconRise = {num(m['aura']['iconRise'])};
    }}
    public const double PopScale = {num(m['popScale'])};
    /// <summary>{m['hoverIntent']['doc']}</summary>
    public const double HoverIntent = {num(m['hoverIntent']['delay'])};
    /// <summary>{m['doneHold']['doc']}</summary>
    public const double DoneHold = {num(m['doneHold']['delay'])};
    /// <summary>{m['checkDraw']['doc']}</summary>
    public const double CheckDraw = {num(m['checkDraw']['duration'])};
    /// <summary>{m['entrance']['doc']}</summary>
    public static class Entrance
    {{
        public const double Stagger = {num(m['entrance']['stagger'])};
        public const double Rise = {num(m['entrance']['rise'])};
        public const double CardScale = {num(m['entrance']['cardScale'])};
        public const double WindowFade = {num(m['entrance']['windowFade'])};
        public const double ReducedFade = {num(m['entrance']['reducedFade'])};
    }}
    /// <summary>{m['wordmark']['doc']}</summary>
    public static class Wordmark
    {{
        public const double LetterStagger = {num(m['wordmark']['letterStagger'])};
        public const double LetterDuration = {num(m['wordmark']['letterDuration'])};
        public const double StaggerCap = {num(m['wordmark']['staggerCap'])};
        public const double Rise = {num(m['wordmark']['rise'])};
        public const double Spread = {num(m['wordmark']['spread'])};
        public const double Blur = {num(m['wordmark']['blur'])};
    }}
}}
'''
    sizes = tokens['typography']['sizes']
    out['windows/src/Mica.Design/Tokens/TypeScale.g.cs'] = cs + '/// <summary>Font sizes in DIPs, equal to points on macOS.</summary>\npublic static class TypeScale\n{\n' + ''.join(
        f'    public const double {k[0].upper() + k[1:]} = {num(v)};\n' for k, v in sizes.items()) + '}\n'
    # Profile icon pack and background presets
    profiles = json.loads((shared / 'profiles.json').read_text())
    phead = '// ' + HEADER.format(src='profiles.json') + '\n'
    def swift_list(items): return '[' + ', '.join(f'"{i}"' for i in items) + ']'
    def cs_list(items): return '[' + ', '.join(f'"{i}"' for i in items) + ']'
    out['macos/Sources/MicaCore/Preferences/ProfileCatalog.swift'] = phead + f'''import Foundation

/// Icons (SF Symbol names, Segoe Fluent pairs in shared/glyphs.json) and background presets for profiles.
public enum ProfileCatalog {{
    public static let icons = {swift_list(profiles['icons'])}
    public static let backgrounds = {swift_list(profiles['backgrounds'])}
    public static let standardIcon = "{profiles['standard']['icon']}"
    public static let standardBackground = "{profiles['standard']['background']}"
}}
'''
    out['windows/src/Mica.Core/Preferences/ProfileCatalog.g.cs'] = phead + f'''namespace Mica.Core;

/// <summary>Icons (SF Symbol names mapped to Segoe Fluent in shared/glyphs.json) and background presets for profiles.</summary>
public static class ProfileCatalog
{{
    public static readonly IReadOnlyList<string> Icons = {cs_list(profiles['icons'])};
    public static readonly IReadOnlyList<string> Backgrounds = {cs_list(profiles['backgrounds'])};
    public const string StandardIcon = "{profiles['standard']['icon']}";
    public const string StandardBackground = "{profiles['standard']['background']}";
}}
'''
    # English text
    rows =(shared / 'strings' / 'en.txt').read_text().split('\n')
    seen = set()
    for number, row in enumerate(rows, 1):
        if not row: continue
        parts = row.split('⟩')
        if len(parts) != 3: sys.exit(f'shared/strings/en.txt:{number}: expected Russian⟩english low⟩English regular')
        if '\\u{' in row: sys.exit(f'shared/strings/en.txt:{number}: escapes are not decoded, write the character itself')
        if parts[0] in seen: sys.exit(f'shared/strings/en.txt:{number}: duplicate key {parts[0]!r}')
        seen.add(parts[0])
    body = '\n'.join(r for r in rows if r).replace('\\', '\\\\')
    out['macos/Sources/MicaCore/Localization/English.swift'] = '// ' + HEADER.format(src='strings/en.txt') + '''
import Foundation

/// English interface text, keyed by the regular Russian variant written at the call site.
/// Each line: Russian regular ⟩ English lowercase style ⟩ English regular. Spaces at the ends are significant.
public enum English {
    public static let table: [String: (low: String, regular: String)] = {
        var result: [String: (low: String, regular: String)] = [:]
        for line in source.split(separator: "\\n", omittingEmptySubsequences: true) {
            let parts = line.components(separatedBy: "⟩")
            guard parts.count == 3 else { continue }
            result[parts[0]] = (parts[1], parts[2])
        }
        return result
    }()
    static let source = """
''' + body + '\n"""\n}\n'
    # Web shell of the Windows app (windows/shell): the same tokens as CSS custom properties and ES modules.
    def css_color(value):
        rgb, alpha = color(value)
        r, g, b = (rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255
        return f'#{rgb:06X}' if alpha == 1 else f'rgb({r} {g} {b} / {num(alpha)})'
    def css_name(name):
        return re.sub(r'([A-Z])', lambda match: '-' + match.group(1).lower(), name)
    def block(selector, pick):
        rows = [f'  --{css_name(name)}: {css_color(pick(e))};' for name, e in tokens['palette'].items()]
        return selector + ' {\n' + '\n'.join(rows) + '\n}\n'
    css = ['/* ' + HEADER.format(src='tokens.json') + ' */',
           block(':root', lambda e: e['light']),
           block(':root[data-theme="dark"]', lambda e: e['dark']),
           block(':root[data-contrast="more"]', lambda e: e.get('contrastLight', e['light'])),
           block(':root[data-theme="dark"][data-contrast="more"]', lambda e: e.get('contrastDark', e['dark'])),
           ':root {']
    for group in ('chrome', 'space', 'radius'):
        for key, entry in tokens[group].items():
            value, _ = value_doc(entry)
            css.append(f'  --{group}-{css_name(key)}: {num(value)}px;')
    for key, value in tokens['typography']['sizes'].items():
        css.append(f'  --type-{css_name(key)}: {num(value)}px;')
    css.append(f'  --hover-duration: {num(m["hover"]["duration"])}s;')
    css.append('}\n')
    out['windows/shell/css/tokens.g.css'] = '\n'.join(css)
    plain = {group: {key: value_doc(entry)[0] for key, entry in tokens[group].items()} for group in ('chrome', 'space', 'radius')}
    motion = {key: ({k: v for k, v in value.items() if k != 'doc'} if isinstance(value, dict) else value) for key, value in m.items()}
    keymap = json.loads((shared / 'keymap.json').read_text())['commands']
    glyph_names = sorted(json.loads((shared / 'glyphs.json').read_text())['glyphs'])
    js = '// ' + HEADER.format(src='tokens.json, keymap.json, profiles.json, glyphs.json and version.txt') + '\n'
    js += 'export const version = ' + json.dumps(version) + ';\n'
    js += 'export const geometry = ' + json.dumps(plain, indent=2) + ';\n'
    js += 'export const motion = ' + json.dumps(motion, indent=2) + ';\n'
    js += 'export const palette = ' + json.dumps({name: {k: v for k, v in e.items() if k != 'doc'} for name, e in tokens['palette'].items()}, indent=2) + ';\n'
    js += 'export const keymap = ' + json.dumps({command: keys['windows'] for command, keys in keymap.items()}, indent=2) + ';\n'
    js += 'export const profileCatalog = ' + json.dumps({'icons': profiles['icons'], 'backgrounds': profiles['backgrounds'], 'standard': profiles['standard']}, indent=2) + ';\n'
    js += 'export const glyphNames = ' + json.dumps(glyph_names) + ';\n'
    out['windows/shell/js/gen/tokens.g.js'] = js
    table = {}
    for row in rows:
        if not row: continue
        key, low, regular = row.split('⟩')
        table[key] = [low, regular]
    out['windows/shell/js/gen/strings.g.js'] = ('// ' + HEADER.format(src='strings/en.txt') + '\n'
        '// English interface text keyed by the regular Russian variant: [lowercase style, regular].\n'
        'export const english = ' + json.dumps(table, ensure_ascii=False, indent=0) + ';\n')
    # A small offline icon catalog shared by both native hosts. The artwork stays in shared/favicons/.
    favicon_catalog = json.loads((shared / 'favicons/catalog.json').read_text())
    favicon_sites, favicon_pixels = favicon_catalog['sites'], favicon_catalog['pixels']
    if not isinstance(favicon_pixels, int) or not 32 <= favicon_pixels <= 256: sys.exit('invalid shared favicon size')
    favicon_files = {host: entry['file'] for host, entry in favicon_sites.items()}
    for host, file in favicon_files.items():
        if not re.fullmatch(r'[a-z0-9.-]+', host) or not re.fullmatch(r'[a-z0-9.-]+\.png', file):
            sys.exit('invalid shared favicon catalog entry')
        if not (shared / 'favicons' / file).is_file(): sys.exit('missing bundled favicon: ' + file)
    head_icons = '// ' + HEADER.format(src='favicons/catalog.json') + '\n'
    out['macos/Sources/MicaCore/Address/FaviconCatalog.swift'] = head_icons + 'public enum FaviconCatalog {\n' + f'    /// {favicon_catalog["pixelsDoc"]}\n    public static let pixels = {favicon_pixels}\n' + '    public static let files: [String: String] = [\n' + ''.join(f'        "{host}": "{file}",\n' for host, file in sorted(favicon_files.items())) + '    ]\n}\n'
    out['windows/src/Mica.Core/Address/FaviconCatalog.g.cs'] = head_icons + 'namespace Mica.Core;\n\npublic static class FaviconCatalog\n{\n' + f'    /// <summary>{favicon_catalog["pixelsDoc"]}</summary>\n    public const int Pixels = {favicon_pixels};\n' + '    public static readonly IReadOnlyDictionary<string, string> Files = new Dictionary<string, string>\n    {\n' + ''.join(f'        ["{host}"] = "{file}",\n' for host, file in sorted(favicon_files.items())) + '    };\n}\n'
    return out

def main():
    check = '--check' in sys.argv
    stale = []
    for relative, text in generate().items():
        path = root / relative
        if path.exists() and path.read_text() == text: continue
        if check: stale.append(relative); continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print('wrote', relative)
    if stale:
        sys.exit('generated files differ from shared/, run scripts/generate.py:\n  ' + '\n  '.join(stale))

if __name__ == '__main__':
    main()
