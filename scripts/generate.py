#!/usr/bin/env python3
"""Writes platform code from shared/: design tokens and English interface text.

  scripts/generate.py          regenerate every output
  scripts/generate.py --check  exit 1 when a generated file differs from shared/ (CI and builds)

Outputs are committed so each platform builds without Python; never edit them by hand.
"""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
shared = root / 'shared'
HEADER = 'Generated by scripts/generate.py from shared/{src}. Do not edit.'

def color(value):
    hexpart, _, alpha = value.partition('/')
    return int(hexpart[1:], 16), float(alpha) if alpha else 1.0

def value_doc(entry):
    return (entry['value'], entry.get('doc')) if isinstance(entry, dict) else (entry, None)

def num(v):
    return str(int(v)) if float(v).is_integer() else repr(float(v))

def swift_rgb(value):
    rgb, alpha = color(value)
    return f'rgb(0x{rgb:06X})' if alpha == 1 else f'rgb(0x{rgb:06X}, {num(alpha)})'

def cs_argb(value):
    rgb, alpha = color(value)
    return f'0x{round(alpha * 255):02X}{rgb:06X}'

def generate():
    tokens = json.loads((shared / 'tokens.json').read_text())
    out = {}
    version = (shared / 'version.txt').read_text().strip()
    if not re.fullmatch(r'\d+\.\d+\.\d+', version):
        sys.exit('shared/version.txt must contain a three-part numeric version')
    for path in ('macos/Resources/App/Info.plist', 'macos/Sources/MicaDockTile/Info.plist'):
        plist = (root / path).read_text()
        updated, count = re.subn(r'(<key>CFBundleShortVersionString</key>\s*<string>)[^<]+(</string>)',
                                 lambda match: match.group(1) + version + match.group(2), plist)
        if count != 1: sys.exit(f'{path}: expected one CFBundleShortVersionString')
        out[path] = updated
    head = '// ' + HEADER.format(src='tokens.json') + '\n'
    # Swift palette
    lines = [head + 'import AppKit\nimport SwiftUI\n', '/// Light: bright paper shell around a pure white page and panels, near-black neutral ink, light hairlines',
             '/// and soft shadows doing the separation. Dark: warm stone. Both resolve per appearance, Increase Contrast included.', 'enum Palette {']
    for name, e in tokens['palette'].items():
        if 'doc' in e: lines.append(f'    /// {e["doc"]}')
        extra = ''.join(f', {k}: {swift_rgb(e[k])}' for k in ('contrastLight', 'contrastDark') if k in e)
        lines.append(f'    static let {name} = Color.dynamic({swift_rgb(e["light"])}, {swift_rgb(e["dark"])}{extra})')
    lines.append('}\n')
    out['macos/Sources/MicaApp/DesignSystem/Tokens/Palette.swift'] = '\n'.join(lines)
    # Swift geometry
    lines = [head + 'import CoreGraphics\n', '// mica design system: paper-white light and warm stone dark themes, ink primary, soft concentric geometry.',
             '// Every reusable control owns only its own shape; parents own spacing.\n']
    titles = {'chrome': ('Chrome', 'Window chrome geometry. The standard window buttons sit on the vertical center of `bar`.'),
              'space': ('Space', 'Spacing scale.'), 'radius': ('Radius', 'Concentric radii: an inner shape uses the outer radius minus the padding between them.')}
    for group, (type_name, doc) in titles.items():
        lines.append(f'/// {doc}\nenum {type_name} {{')
        for key, entry in tokens[group].items():
            value, d = value_doc(entry)
            if d: lines.append(f'    /// {d}')
            lines.append(f'    static let {key}: CGFloat = {num(value)}')
        lines.append('}\n')
    out['macos/Sources/MicaApp/DesignSystem/Tokens/Geometry.swift'] = '\n'.join(lines)
    m = tokens['motion']
    out['macos/Sources/MicaApp/DesignSystem/Tokens/MotionTokens.swift'] = head + f'''import Foundation

/// Spring parameters in SwiftUI terms: response in seconds, damping fraction. Windows converts them in Mica.Design.
enum MotionTokens {{
    /// {m['hover']['doc']}
    static let hoverDuration = {num(m['hover']['duration'])}
    static let press = (response: {num(m['press']['response'])}, damping: {num(m['press']['damping'])})
    static let snappy = (response: {num(m['snappy']['response'])}, damping: {num(m['snappy']['damping'])})
    static let panel = (response: {num(m['panel']['response'])}, damping: {num(m['panel']['damping'])})
    static let popScale = {num(m['popScale'])}
}}
'''
    # C#
    cs = '// ' + HEADER.format(src='tokens.json') + '\nnamespace Mica.Design;\n\n'
    lines = [cs + '/// <summary>Light, dark and high-contrast variants as 0xAARRGGBB.</summary>', 'public static partial class Palette', '{']
    for name, e in tokens['palette'].items():
        if 'doc' in e: lines.append(f'    /// <summary>{e["doc"]}</summary>')
        cl = cs_argb(e.get('contrastLight', e['light'])); cd = cs_argb(e.get('contrastDark', e['dark']))
        lines.append(f'    public static readonly Swatch {name[0].upper() + name[1:]} = new({cs_argb(e["light"])}, {cs_argb(e["dark"])}, {cl}, {cd});')
    lines.append('}\n')
    out['windows/src/Mica.Design/Tokens/Palette.g.cs'] = '\n'.join(lines)
    lines = [cs]
    for group, (type_name, doc) in titles.items():
        lines.append(f'/// <summary>{doc}</summary>\npublic static class {type_name}\n{{')
        for key, entry in tokens[group].items():
            value, d = value_doc(entry)
            if d: lines.append(f'    /// <summary>{d}</summary>')
            lines.append(f'    public const double {key[0].upper() + key[1:]} = {num(value)};')
        lines.append('}\n')
    out['windows/src/Mica.Design/Tokens/Geometry.g.cs'] = '\n'.join(lines)
    out['windows/src/Mica.Design/Tokens/MotionTokens.g.cs'] = cs + f'''/// <summary>Spring parameters in SwiftUI terms (response seconds, damping fraction), converted by <see cref="Motion"/>.</summary>
public static class MotionTokens
{{
    /// <summary>{m['hover']['doc']}</summary>
    public const double HoverDuration = {num(m['hover']['duration'])};
    public static readonly Spring Press = new({num(m['press']['response'])}, {num(m['press']['damping'])});
    public static readonly Spring Snappy = new({num(m['snappy']['response'])}, {num(m['snappy']['damping'])});
    public static readonly Spring Panel = new({num(m['panel']['response'])}, {num(m['panel']['damping'])});
    public const double PopScale = {num(m['popScale'])};
}}
'''
    sizes = tokens['typography']['sizes']
    out['windows/src/Mica.Design/Tokens/TypeScale.g.cs'] = cs + '/// <summary>Font sizes in DIPs, equal to points on macOS.</summary>\npublic static class TypeScale\n{\n' + ''.join(
        f'    public const double {k[0].upper() + k[1:]} = {num(v)};\n' for k, v in sizes.items()) + '}\n'
    # English text
    rows = (shared / 'strings' / 'en.txt').read_text().split('\n')
    seen = set()
    for number, row in enumerate(rows, 1):
        if not row: continue
        parts = row.split('⟩')
        if len(parts) != 3: sys.exit(f'shared/strings/en.txt:{number}: expected Russian⟩english low⟩English regular')
        if parts[0] in seen: sys.exit(f'shared/strings/en.txt:{number}: duplicate key {parts[0]!r}')
        seen.add(parts[0])
    body = '\n'.join(r for r in rows if r).replace('\\', '\\\\')
    out['macos/Sources/MicaCore/Localization/English.swift'] = '// ' + HEADER.format(src='strings/en.txt') + '''
import Foundation

/// English interface text, keyed by the regular Russian variant written at the call site.
/// Each line: Russian regular ⟩ English lowercase style ⟩ English regular. Spaces at the ends are significant.
public enum English {
    public static let table: [String: (low: String, regular: String)] = {
        var result: [String: (low: String, regular: String)] = [:]
        for line in source.split(separator: "\\n", omittingEmptySubsequences: true) {
            let parts = line.components(separatedBy: "⟩")
            guard parts.count == 3 else { continue }
            result[parts[0]] = (parts[1], parts[2])
        }
        return result
    }()
    static let source = """
''' + body + '\n"""\n}\n'
    return out

def main():
    check = '--check' in sys.argv
    stale = []
    for relative, text in generate().items():
        path = root / relative
        if path.exists() and path.read_text() == text: continue
        if check: stale.append(relative); continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print('wrote', relative)
    if stale:
        sys.exit('generated files differ from shared/, run scripts/generate.py:\n  ' + '\n  '.join(stale))

if __name__ == '__main__':
    main()
